import type { SQLiteDatabase } from "expo-sqlite";

/**
 * Bump this and add a step below whenever the tables change.
 * SQLite stores the version in `PRAGMA user_version`, so each device only runs the steps it hasn't run yet.
 * Never edit a step that has already shipped; add a new one instead.
 */
const DATABASE_VERSION = 3;

export async function migrateDbIfNeeded(db: SQLiteDatabase): Promise<void> {
  const row = await db.getFirstAsync<{ user_version: number }>("PRAGMA user_version");
  let version = row?.user_version ?? 0;
  if (version >= DATABASE_VERSION) return;

  if (version === 0) {
    // goal and current are stored as JSON text: their shape is still changing,
    // and nothing needs to query inside them yet.
    await db.execAsync(`
      CREATE TABLE habits (
        id TEXT PRIMARY KEY NOT NULL,
        title TEXT NOT NULL,
        color TEXT NOT NULL,
        icon TEXT NOT NULL,
        goal TEXT NOT NULL,
        current TEXT,
        created_at TEXT NOT NULL
      );
    `);
    version = 1;
  }

  if (version === 1) {
    // Ids are now generated by SQLite. AUTOINCREMENT never reuses the id of a deleted row,
    // so a stacked habit can't end up pointing at a different habit.
    // Only test data existed at this point, so the old table is dropped rather than converted.
    await db.withTransactionAsync(async () => {
      await db.execAsync(`
        DROP TABLE habits;
        CREATE TABLE habits (
          id INTEGER PRIMARY KEY AUTOINCREMENT,
          title TEXT NOT NULL,
          color TEXT NOT NULL,
          icon TEXT NOT NULL,
          goal TEXT NOT NULL,
          current TEXT,
          created_at TEXT NOT NULL
        );
      `);
    });
    version = 2;
  }

  if (version === 2) {
    // The goal JSON changed shape: "at a time" goals were removed and count goals now use
    // a frequency instead of an interval. Old goals meant something different and can't be
    // converted reliably; only test data existed, so it is cleared.
    await db.execAsync("DELETE FROM habits;");
    version = 3;
  }

  await db.execAsync(`PRAGMA user_version = ${version}`);
}
